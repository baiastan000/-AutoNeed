let currentLanguage = localStorage.getItem("autoneed-language") || "ru";

function translateText(text) {
  if (currentLanguage === "ru") return text;
  const direct = translations[currentLanguage]?.[text] ?? adminTranslations[currentLanguage]?.[text];
  return direct || text;
}

function applyLanguage(lang) {
  currentLanguage = lang;
  localStorage.setItem("autoneed-language", lang);
  document.documentElement.lang = lang === "ky" ? "ky" : lang;
  document.querySelectorAll("[data-language]").forEach((button) => { button.textContent = lang.toUpperCase(); });
  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  const nodes = [];
  while (walker.nextNode()) nodes.push(walker.currentNode);
  nodes.forEach((node) => {
    if (!node.textContent.trim()) return;
    if (!node.dataset?.original) {
      if (!node.originalText) node.originalText = node.textContent;
    }
  });
  nodes.forEach((node) => {
    const original = node.originalText ?? node.textContent;
    node.originalText = original;
    node.textContent = translateText(original);
  });
  document.querySelectorAll("[placeholder]").forEach((el) => {
    if (!el.dataset.originalPlaceholder) el.dataset.originalPlaceholder = el.placeholder;
    el.placeholder = translateText(el.dataset.originalPlaceholder);
  });
  document.querySelectorAll("[aria-label]").forEach((el) => {
    if (!el.dataset.originalAria) el.dataset.originalAria = el.getAttribute("aria-label");
    el.setAttribute("aria-label", translateText(el.dataset.originalAria));
  });
  renderCategories();
  renderProducts();
  document.documentElement.classList.remove("language-pending");
  closeLanguageMenu();
}

