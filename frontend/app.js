function getProductStats(product) {
  const reviews = get(`reviews-${product.id}`, []);
  if (!reviews.length) return {rating: product.rating, reviews: product.reviews};
  const sum = reviews.reduce((total, review) => total + review.rating, 0);
  const rating = (product.rating * product.reviews + sum) / (product.reviews + reviews.length);
  return {rating, reviews: product.reviews + reviews.length};
}

